package outbox

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"
)

// MigrationSQL returns the CREATE statements for an outbox table named
// tableName. Each adopting service runs this once at startup (or via
// its normal migration tooling) to provision its own outbox table.
//
// Services own their outbox tables (rather than sharing one) because:
//
//  1. The (entity_id, event_type) UNIQUE constraint deduplication is
//     scoped per-service domain — sharing a table would conflate
//     "send.email for notification 1" with "send.email for marketing 1".
//  2. ON DELETE CASCADE FKs reference the service's own entity tables,
//     which aren't co-located across schemas.
//  3. Per-service tables let each service operate (truncate, archive,
//     vacuum, partition) independently.
//
// The table name MUST match [a-z][a-z0-9_]* — we don't quote it so a
// SQL injection via a bad table name would be a developer-side bug;
// callers should hard-code the name in their startup wiring.
func MigrationSQL(tableName string) string {
	return fmt.Sprintf(`
-- =====================================================================
-- Outbox table for %[1]s — generated by platform-shared/outbox.MigrationSQL
--
-- Pattern: Transactional Outbox (microservices.io)
-- See package doc for the full design rationale.
-- =====================================================================

CREATE TABLE IF NOT EXISTS %[1]s (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),

    -- The owning resource's UUID. FK to the service's own entity table
    -- is set up by the adopting service via a follow-up ALTER TABLE.
    entity_id     uuid        NOT NULL,

    -- Discriminator routed to a Handler by the worker. Convention:
    --   "<provider>.<verb>"   e.g. "stripe.create_subscription"
    --                              "smtp.send"
    --                              "cloudflare.publish_dkim"
    event_type    text        NOT NULL,

    payload       jsonb       NOT NULL DEFAULT '{}'::jsonb,

    status        text        NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending','in_progress','delivered','failed')),

    retry_count   integer     NOT NULL DEFAULT 0,
    max_retries   integer     NOT NULL DEFAULT 10,
    next_retry_at timestamptz NOT NULL DEFAULT now(),
    last_error    text,

    claimed_at    timestamptz,
    claimed_by    text,

    delivered_at  timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    UNIQUE (entity_id, event_type)
);

CREATE INDEX IF NOT EXISTS idx_%[1]s_pending_due
    ON %[1]s (next_retry_at)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_%[1]s_in_progress_claimed_at
    ON %[1]s (claimed_at)
    WHERE status = 'in_progress';

CREATE INDEX IF NOT EXISTS idx_%[1]s_entity
    ON %[1]s (entity_id);

CREATE OR REPLACE FUNCTION trg_%[1]s_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $body$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$body$;

DROP TRIGGER IF EXISTS %[1]s_updated_at ON %[1]s;
CREATE TRIGGER %[1]s_updated_at
    BEFORE UPDATE ON %[1]s
    FOR EACH ROW EXECUTE FUNCTION trg_%[1]s_updated_at();
`, tableName)
}

// EnsureSchema runs MigrationSQL against the given pool. Idempotent —
// the CREATE statements all use IF NOT EXISTS / OR REPLACE. Safe to
// call from main() at every startup.
//
// Production deployments should prefer their normal migration tooling
// (Keystone bundle, sqlx-migrate, etc.) and call MigrationSQL during
// authoring rather than at runtime. EnsureSchema is for dev + tests.
func EnsureSchema(ctx context.Context, pool *pgxpool.Pool, tableName string) error {
	if _, err := pool.Exec(ctx, MigrationSQL(tableName)); err != nil {
		return fmt.Errorf("outbox.EnsureSchema(%q): %w", tableName, err)
	}
	return nil
}
