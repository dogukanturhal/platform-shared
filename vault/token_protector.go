const (
	defaultKubernetesTokenPath = "/var/run/secrets/kubernetes.io/serviceaccount/token"
	maxVaultResponseBytes      = 1 << 20
	maxVaultAuthTokenBytes     = 4096
	maxVaultLeaseSeconds       = int64(1<<63-1) / int64(time.Second)
	defaultMaxTokenBytes       = 4096
)

var (
	vaultName    = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$`)
	contextLabel = regexp.MustCompile(`^[a-z][a-z0-9-]{0,62}$`)
	tenantID     = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,63}$`)
	uuid         = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`)
)

// TokenContext is cryptographically bound to a protected payment token. All
// fields are required except that either TenantID or CorrelationID may identify
// a request that is not tenant scoped.
type TokenContext struct {
	ContextVersion string
	Service        string
	Provider       string
	Purpose        string
	TenantID       string
	CorrelationID  string
}

// ProtectedToken is safe to persist. It contains no plaintext or key material.
type ProtectedToken struct {
	Ciphertext string
	KeyVersion int
}

// TokenDigest is a deterministic, versioned HMAC generated by a separate
// Transit HMAC key. It is safe for indexed lookup, not for logging.
type TokenDigest struct {
	Value      string
	KeyID      string
	KeyVersion int
}

// TransitKeyMetadata is the non-secret metadata needed to plan rewraps.
type TransitKeyMetadata struct {
	Name          string
	LatestVersion int
	MinDecryption int
	MinEncryption int
}

// TokenProtector is the deliberately small payment-token boundary.
type TokenProtector interface {
	Protect(context.Context, []byte, TokenContext) (ProtectedToken, error)
	Unprotect(context.Context, ProtectedToken, TokenContext) ([]byte, error)
	Rewrap(context.Context, ProtectedToken, TokenContext) (ProtectedToken, error)
	Digest(context.Context, []byte, TokenContext) (TokenDigest, error)
	VerifyDigest(context.Context, []byte, TokenContext, TokenDigest) (bool, error)
	EncryptionKeyMetadata(context.Context) (TransitKeyMetadata, error)
}

// TokenProtectorConfig is intentionally Kubernetes-only. It never consumes
// VAULT_TOKEN, AppRole credentials, or an environment plaintext fallback.
type TokenProtectorConfig struct {
	Address             string
	AllowedHosts        []string
	TLSCAFile           string
	TLSServerName       string
	Namespace           string
	AuthMethod          string
	AuthMount           string
	KubernetesRole      string
	KubernetesTokenPath string
	TransitMount        string
	EncryptionKey       string
	HMACKey             string
	RequestTimeout      time.Duration
	RenewalWindow       time.Duration
	MaxTokenBytes       int
}

// DefaultTokenProtectorConfig returns required-mode timeout and Transit defaults.
func DefaultTokenProtectorConfig() TokenProtectorConfig {
	return TokenProtectorConfig{
		KubernetesTokenPath: defaultKubernetesTokenPath,
		TransitMount:        "transit",
		AuthMount:           "kubernetes",
		RequestTimeout:      5 * time.Second,
		RenewalWindow:       time.Minute,
		MaxTokenBytes:       defaultMaxTokenBytes,
	}
}

// LoadTokenProtectorConfigFromEnv reads only the required Kubernetes settings.
func LoadTokenProtectorConfigFromEnv() TokenProtectorConfig {
	cfg := DefaultTokenProtectorConfig()
	cfg.Address = os.Getenv("VAULT_ADDR")
	cfg.AllowedHosts = strings.FieldsFunc(os.Getenv("VAULT_ALLOWED_HOSTS"), func(r rune) bool { return r == ',' })
	cfg.TLSCAFile = os.Getenv("VAULT_CACERT")
	cfg.TLSServerName = os.Getenv("VAULT_TLS_SERVER_NAME")
	cfg.Namespace = os.Getenv("VAULT_NAMESPACE")
	cfg.AuthMethod = os.Getenv("VAULT_AUTH_METHOD")
	cfg.KubernetesRole = os.Getenv("VAULT_KUBERNETES_ROLE")
	if v := os.Getenv("VAULT_KUBERNETES_AUTH_MOUNT"); v != "" {
		cfg.AuthMount = v
	}
	if v := os.Getenv("VAULT_KUBERNETES_TOKEN_PATH"); v != "" {
		cfg.KubernetesTokenPath = v
	}
	if v := os.Getenv("VAULT_TRANSIT_MOUNT_PATH"); v != "" {
		cfg.TransitMount = v
	}
	cfg.EncryptionKey = os.Getenv("VAULT_TRANSIT_TOKEN_KEY")
	cfg.HMACKey = os.Getenv("VAULT_TRANSIT_TOKEN_HMAC_KEY")
	if d, err := time.ParseDuration(os.Getenv("VAULT_REQUEST_TIMEOUT")); err == nil && d > 0 {
		cfg.RequestTimeout = d
	}
	if n, err := strconv.Atoi(os.Getenv("VAULT_MAX_TOKEN_BYTES")); err == nil && n > 0 {
		cfg.MaxTokenBytes = n
	}
	return cfg
}

type vaultTokenProtector struct {
	cfg    TokenProtectorConfig
	client *http.Client
	base   *url.URL

	mu           sync.Mutex
	token        string
	expires      time.Time
	refresh      time.Time
	generation   uint64
	failureUntil time.Time
}

// NewTokenProtector creates a required-mode Kubernetes-authenticated protector.
func NewTokenProtector(ctx context.Context, cfg TokenProtectorConfig) (TokenProtector, error) {
	if cfg.MaxTokenBytes == 0 {
		cfg.MaxTokenBytes = defaultMaxTokenBytes
	}
	if cfg.AuthMount == "" {
		cfg.AuthMount = "kubernetes"
	}
	if err := validateTokenProtectorConfig(cfg); err != nil {
		return nil, err
	}
	base, _ := url.Parse(cfg.Address)
	pool := x509.NewCertPool()
	pem, err := os.ReadFile(cfg.TLSCAFile)
	if err != nil || !pool.AppendCertsFromPEM(pem) {
		return nil, errors.New("unable to load Vault CA bundle")
	}
	transport := &http.Transport{TLSClientConfig: &tls.Config{MinVersion: tls.VersionTLS12, RootCAs: pool, ServerName: cfg.TLSServerName}}
	client := &http.Client{Timeout: cfg.RequestTimeout, Transport: transport, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}
	p := &vaultTokenProtector{cfg: cfg, client: client, base: base}
	if err := p.ensureToken(ctx); err != nil {
		return nil, fmt.Errorf("vault token protector authentication failed: %w", err)
	}
	return p, nil
}

func validateTokenProtectorConfig(cfg TokenProtectorConfig) error {
	if cfg.AuthMethod != "kubernetes" {
		return errors.New("vault token protector requires VAULT_AUTH_METHOD=kubernetes")
	}
	u, err := url.ParseRequestURI(cfg.Address)
	if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || u.Path != "" && u.Path != "/" {
		return errors.New("vault token protector requires a valid VAULT_ADDR")
	}
	if len(cfg.AllowedHosts) == 0 || !approvedHost(u.Host, cfg.AllowedHosts) {
		return errors.New("vault endpoint host is not approved")
	}
	if strings.TrimSpace(cfg.TLSCAFile) == "" || cfg.RequestTimeout <= 0 || cfg.RenewalWindow < 0 || cfg.MaxTokenBytes < 1 || cfg.MaxTokenBytes > 65536 {
		return errors.New("vault token protector requires positive bounded timeouts")
	}
	for label, value := range map[string]string{"kubernetes role": cfg.KubernetesRole, "auth mount": cfg.AuthMount, "transit mount": cfg.TransitMount, "encryption key": cfg.EncryptionKey, "hmac key": cfg.HMACKey} {
		if !vaultName.MatchString(value) {
			return fmt.Errorf("invalid vault %s", label)
		}
	}
	if strings.TrimSpace(cfg.KubernetesTokenPath) == "" {
		return errors.New("kubernetes projected token path is required")
	}
	return nil
}

func approvedHost(host string, allowed []string) bool {
	for _, candidate := range allowed {
		if host == strings.TrimSpace(candidate) {
			return true
		}
	}
	return false
}

func (p *vaultTokenProtector) Protect(ctx context.Context, plaintext []byte, binding TokenContext) (ProtectedToken, error) {
	encodedContext, err := encodeTokenContext(binding)
	if err != nil || len(plaintext) == 0 || len(plaintext) > p.cfg.MaxTokenBytes {
		return ProtectedToken{}, errors.New("refusing to protect empty token")
	}
	data, err := p.write(ctx, "encrypt", p.cfg.EncryptionKey, map[string]string{"plaintext": base64.StdEncoding.EncodeToString(plaintext), "context": encodedContext})
	if err != nil {
		return ProtectedToken{}, err
	}
	ciphertext, ok := data["ciphertext"].(string)
	version, okv := transitVersion(ciphertext)
	if !ok || !okv {
		return ProtectedToken{}, errors.New("malformed transit encryption response")
	}
	if responseVersion, present := responseVersion(data); present && responseVersion != version {
		return ProtectedToken{}, errors.New("transit encryption version mismatch")
	}
	if responseKey, present := responseKeyID(data); present && responseKey != p.cfg.EncryptionKey {
		return ProtectedToken{}, errors.New("transit encryption key mismatch")
	}
	return ProtectedToken{Ciphertext: ciphertext, KeyVersion: version}, nil
}

func (p *vaultTokenProtector) Unprotect(ctx context.Context, token ProtectedToken, binding TokenContext) ([]byte, error) {
	encodedContext, err := encodeTokenContext(binding)
	version, validVersion := transitVersion(token.Ciphertext)
	if !validVersion || token.KeyVersion != version {
		return nil, errors.New("invalid protected token")
	}
	if err != nil {
		return nil, errors.New("invalid token context")
	}
	data, err := p.write(ctx, "decrypt", p.cfg.EncryptionKey, map[string]string{"ciphertext": token.Ciphertext, "context": encodedContext})
	if err != nil {
		return nil, err
	}
	encoded, ok := data["plaintext"].(string)
	if !ok || encoded == "" {
		return nil, errors.New("malformed transit decryption response")
	}
	plaintext, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil || len(plaintext) == 0 || len(plaintext) > p.cfg.MaxTokenBytes {
		return nil, errors.New("malformed transit plaintext response")
	}
	return plaintext, nil
}

func (p *vaultTokenProtector) Rewrap(ctx context.Context, token ProtectedToken, binding TokenContext) (ProtectedToken, error) {
	encodedContext, err := encodeTokenContext(binding)
	version, validVersion := transitVersion(token.Ciphertext)
	if !validVersion || token.KeyVersion != version {
		return ProtectedToken{}, errors.New("invalid protected token")
	}
	if err != nil {
		return ProtectedToken{}, errors.New("invalid token context")
	}
	data, err := p.write(ctx, "rewrap", p.cfg.EncryptionKey, map[string]string{"ciphertext": token.Ciphertext, "context": encodedContext})
	if err != nil {
		return ProtectedToken{}, err
	}
	ciphertext, ok := data["ciphertext"].(string)
	version, okv := transitVersion(ciphertext)
	if !ok || !okv {
		return ProtectedToken{}, errors.New("malformed transit rewrap response")
	}
	if responseVersion, present := responseVersion(data); present && responseVersion != version {
		return ProtectedToken{}, errors.New("transit rewrap version mismatch")
	}
	if responseKey, present := responseKeyID(data); present && responseKey != p.cfg.EncryptionKey {
		return ProtectedToken{}, errors.New("transit rewrap key mismatch")
	}
	return ProtectedToken{Ciphertext: ciphertext, KeyVersion: version}, nil
}

func (p *vaultTokenProtector) Digest(ctx context.Context, token []byte, binding TokenContext) (TokenDigest, error) {
	encodedContext, err := encodeTokenContext(binding)
	if err != nil || len(token) == 0 || len(token) > p.cfg.MaxTokenBytes {
		return TokenDigest{}, errors.New("refusing to digest empty token")
	}
	data, err := p.write(ctx, "hmac", p.cfg.HMACKey, map[string]string{"input": base64.StdEncoding.EncodeToString(token), "context": encodedContext, "algorithm": "sha2-256"})
	if err != nil {
		return TokenDigest{}, err
	}
	value, ok := data["hmac"].(string)
	version, okv := transitVersion(value)
	if !ok || !okv {
		return TokenDigest{}, errors.New("malformed transit hmac response")
	}
	if responseVersion, present := responseVersion(data); present && responseVersion != version {
		return TokenDigest{}, errors.New("transit hmac version mismatch")
	}
	if responseKey, present := responseKeyID(data); present && responseKey != p.cfg.HMACKey {
		return TokenDigest{}, errors.New("transit hmac key mismatch")
	}
	return TokenDigest{Value: value, KeyID: p.cfg.HMACKey, KeyVersion: version}, nil
}

func (p *vaultTokenProtector) VerifyDigest(ctx context.Context, token []byte, binding TokenContext, digest TokenDigest) (bool, error) {
	encodedContext, err := encodeTokenContext(binding)
	if len(token) == 0 || len(token) > p.cfg.MaxTokenBytes || digest.KeyVersion < 1 || digest.KeyID != p.cfg.HMACKey {
		return false, errors.New("invalid token digest")
	}
	if _, ok := transitVersion(digest.Value); !ok {
		return false, errors.New("invalid token digest")
	}
	if err != nil {
		return false, errors.New("invalid token context")
	}
	if version, _ := transitVersion(digest.Value); version != digest.KeyVersion {
		return false, errors.New("token digest version mismatch")
	}
	data, err := p.write(ctx, "verify", p.cfg.HMACKey, map[string]string{"input": base64.StdEncoding.EncodeToString(token), "context": encodedContext, "hmac": digest.Value, "algorithm": "sha2-256"})
	if err != nil {
		return false, err
	}
	valid, ok := data["valid"].(bool)
	if !ok {
		return false, errors.New("malformed transit hmac verification response")
	}
	return valid, nil
}

// DigestEqual is for local comparisons of stored digests.
func DigestEqual(a, b TokenDigest) bool {
	return a.KeyID == b.KeyID && a.KeyVersion == b.KeyVersion && subtle.ConstantTimeCompare([]byte(a.Value), []byte(b.Value)) == 1
}

func (p *vaultTokenProtector) EncryptionKeyMetadata(ctx context.Context) (TransitKeyMetadata, error) {
	data, err := p.read(ctx, "keys", p.cfg.EncryptionKey)
	if err != nil {
		return TransitKeyMetadata{}, err
	}
	latest, ok := integer(data["latest_version"])
	if !ok || latest < 1 {
		return TransitKeyMetadata{}, errors.New("malformed transit key metadata")
	}
	minDecrypt, _ := integer(data["min_decryption_version"])
	minEncrypt, _ := integer(data["min_encryption_version"])
	return TransitKeyMetadata{Name: p.cfg.EncryptionKey, LatestVersion: latest, MinDecryption: minDecrypt, MinEncryption: minEncrypt}, nil
}

func encodeTokenContext(c TokenContext) (string, error) {
	if c.ContextVersion != "v1" || !contextLabel.MatchString(c.Service) || !contextLabel.MatchString(c.Provider) || !contextLabel.MatchString(c.Purpose) || (c.TenantID == "" && c.CorrelationID == "") || (c.TenantID != "" && !tenantID.MatchString(c.TenantID)) || (c.CorrelationID != "" && !uuid.MatchString(c.CorrelationID)) {
		return "", errors.New("service, provider, purpose, and tenant or correlation identity are required")
	}
	// Struct field order makes the encoded JSON stable across processes and Go versions.
	b, _ := json.Marshal(struct {
		ContextVersion string `json:"context_version"`
		Service        string `json:"service"`
		Provider       string `json:"provider"`
		Purpose        string `json:"purpose"`
		TenantID       string `json:"tenant_id,omitempty"`
		CorrelationID  string `json:"correlation_id,omitempty"`
	}{c.ContextVersion, c.Service, c.Provider, c.Purpose, c.TenantID, c.CorrelationID})
	return base64.StdEncoding.EncodeToString(b), nil
}

func (p *vaultTokenProtector) write(ctx context.Context, operation, key string, body map[string]string) (map[string]any, error) {
	return p.request(ctx, http.MethodPost, p.cfg.TransitMount+"/"+operation+"/"+key, body)
}
func (p *vaultTokenProtector) read(ctx context.Context, operation, key string) (map[string]any, error) {
	return p.request(ctx, http.MethodGet, p.cfg.TransitMount+"/"+operation+"/"+key, nil)
}
func (p *vaultTokenProtector) request(ctx context.Context, method, path string, body any) (map[string]any, error) {
	if err := p.ensureToken(ctx); err != nil {
		return nil, err
	}
	token, generation := p.currentAuth()
	data, status, err := p.do(ctx, method, "/v1/"+path, body, token)
	if err == nil {
		return data, nil
	}
	if status == http.StatusForbidden || status == http.StatusUnauthorized {
		p.mu.Lock()
		if p.generation == generation {
			p.expires, p.refresh = time.Time{}, time.Time{}
		}
		p.mu.Unlock()
		if authErr := p.ensureToken(ctx); authErr != nil {
			return nil, authErr
		}
		token, _ = p.currentAuth()
		data, _, err = p.do(ctx, method, "/v1/"+path, body, token)
	}
	if err != nil {
		return nil, errors.New("vault transit request failed")
	}
	return data, nil
}

func (p *vaultTokenProtector) ensureToken(ctx context.Context) error {
	p.mu.Lock()
	defer p.mu.Unlock()
	if time.Now().Before(p.failureUntil) {
		return errors.New("vault authentication unavailable")
	}
	if !p.refresh.IsZero() && time.Now().Before(p.refresh) {
		return nil
	}
	if p.token != "" && !p.expires.IsZero() {
		data, _, err := p.do(ctx, http.MethodPost, "/v1/auth/token/renew-self", map[string]any{}, p.token)
		if err == nil {
			if token, lease, ok := vaultAuthLease(data, false, true); ok {
				if token != "" && token != p.token {
					p.token = token
					p.generation++
				}
				p.setLeaseLocked(lease)
				return nil
			}
		}
	}
	jwt, err := os.ReadFile(p.cfg.KubernetesTokenPath)
	if err != nil || len(bytes.TrimSpace(jwt)) == 0 {
		p.failureUntil = time.Now().Add(time.Second)
		return errors.New("unable to read Kubernetes service account token")
	}
	data, _, err := p.do(ctx, http.MethodPost, "/v1/auth/"+p.cfg.AuthMount+"/login", map[string]string{"role": p.cfg.KubernetesRole, "jwt": string(bytes.TrimSpace(jwt))}, "")
	if err != nil {
		p.failureUntil = time.Now().Add(time.Second)
		return errors.New("vault Kubernetes login failed")
	}
	token, lease, ok := vaultAuthLease(data, true, false)
	if !ok {
		p.failureUntil = time.Now().Add(time.Second)
		return errors.New("malformed vault Kubernetes login response")
	}
	p.token = token
	p.generation++
	p.failureUntil = time.Time{}
	p.setLeaseLocked(lease)
	return nil
}

// setLeaseLocked updates both deadlines atomically while ensureToken holds p.mu.
func (p *vaultTokenProtector) setLeaseLocked(lease int) {
	duration := time.Duration(lease) * time.Second
	p.expires = time.Now().Add(duration)
	window := p.cfg.RenewalWindow
	if half := duration / 2; window > half {
		window = half
	}
	p.refresh = p.expires.Add(-window)
}

// vaultAuthLease accepts only the bounded auth fields that affect token use.
// A renewed token must explicitly be renewable; Kubernetes login responses may
// omit that field because Vault can issue non-renewable login tokens.
func vaultAuthLease(data map[string]any, requireToken, requireRenewable bool) (string, int, bool) {
	auth, ok := data["auth"].(map[string]any)
	if !ok || len(auth) == 0 {
		return "", 0, false
	}
	lease, ok := integer(auth["lease_duration"])
	if !ok || lease <= 0 || int64(lease) > maxVaultLeaseSeconds {
		return "", 0, false
	}
	if requireRenewable {
		renewable, ok := auth["renewable"].(bool)
		if !ok || !renewable {
			return "", 0, false
		}
	}
	token, present := auth["client_token"]
	if !present {
		return "", lease, !requireToken
	}
	clientToken, ok := token.(string)
	if !ok || len(clientToken) == 0 || len(clientToken) > maxVaultAuthTokenBytes || strings.TrimSpace(clientToken) != clientToken || strings.ContainsAny(clientToken, "\r\n") {
		return "", 0, false
	}
	return clientToken, lease, true
}

func (p *vaultTokenProtector) currentAuth() (string, uint64) {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.token, p.generation
}

func (p *vaultTokenProtector) do(ctx context.Context, method, path string, payload any, token string) (map[string]any, int, error) {
	var body io.Reader
	if payload != nil {
		b, err := json.Marshal(payload)
		if err != nil {
			return nil, 0, err
		}
		body = bytes.NewReader(b)
	}
	requestCtx, cancel := context.WithTimeout(ctx, p.cfg.RequestTimeout)
	defer cancel()
	req, err := http.NewRequestWithContext(requestCtx, method, p.base.ResolveReference(&url.URL{Path: path}).String(), body)
	if err != nil {
		return nil, 0, err
	}
	req.Header.Set("Content-Type", "application/json")
	if p.cfg.Namespace != "" {
		req.Header.Set("X-Vault-Namespace", p.cfg.Namespace)
	}
	if token != "" {
		req.Header.Set("X-Vault-Token", token)
	}
	resp, err := p.client.Do(req)
	if err != nil {
		return nil, 0, err
	}
	defer func() { _ = resp.Body.Close() }()
	raw, err := io.ReadAll(io.LimitReader(resp.Body, maxVaultResponseBytes+1))
	if err != nil || len(raw) > maxVaultResponseBytes {
		return nil, resp.StatusCode, errors.New("invalid vault response")
	}
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil, resp.StatusCode, errors.New("vault response status")
	}
	var envelope struct {
		Data map[string]any `json:"data"`
		Auth map[string]any `json:"auth"`
	}
	if json.Unmarshal(raw, &envelope) != nil {
		return nil, resp.StatusCode, errors.New("invalid vault response")
	}
	if envelope.Data != nil {
		return envelope.Data, resp.StatusCode, nil
	}
	if envelope.Auth != nil {
		return map[string]any{"auth": envelope.Auth}, resp.StatusCode, nil
	}
	return nil, resp.StatusCode, errors.New("empty vault response")
}

func transitVersion(value string) (int, bool) {
	parts := strings.Split(value, ":")
	if len(parts) < 3 || parts[0] != "vault" || !strings.HasPrefix(parts[1], "v") {
		return 0, false
	}
	v, err := strconv.Atoi(strings.TrimPrefix(parts[1], "v"))
	return v, err == nil && v > 0 && parts[2] != ""
}
func responseVersion(data map[string]any) (int, bool) { return integer(data["key_version"]) }
func responseKeyID(data map[string]any) (string, bool) {
	value, ok := data["key_id"].(string)
	return value, ok
}
func integer(v any) (int, bool) { n, ok := v.(float64); return int(n), ok && n == float64(int(n)) }
